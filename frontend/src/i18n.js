const current = ref('zh')

export function setLang(lang) {
  current.value = lang === 'en' ? 'en' : 'zh'
  if (typeof document !== 'undefined') {
    document.documentElement.setAttribute('lang', current.value === 'en' ? 'en' : 'zh-CN')
  }
}

export function lang() {
  return current.value
}

export function t(key) {
  if (current.value === 'en' && en[key] !== undefined) return en[key]
  return zh[key] !== undefined ? zh[key] : key
}

/** {0} {1} 占位替换，与旧版 MessageFormat 行为一致。 */
export function tf(key, ...args) {
  let s = t(key)
  for (let i = 0; i < args.length; i++) {
    s = s.replace(new RegExp('\\{' + i + '\\}', 'g'), String(args[i]))
  }
  return s
}
